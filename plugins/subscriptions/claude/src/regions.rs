/// Whether `loc` is listed, or a territory of a listed country.
pub(crate) fn supported_loc(loc: &str) -> bool {
    if supported_name(loc).is_some() {
        return true;
    }
    territory_of(loc).is_some_and(|parent| supported_name(parent).is_some())
}

